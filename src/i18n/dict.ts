export type MessageKey = keyof typeof DICT;
export type Locale = "en" | "pt-BR";
export const LOCALES: Locale[] = ["en", "pt-BR"];
export const LOCALE_LABEL: Record<Locale, string> = { en: "English", "pt-BR": "Português (Brasil)" };
export const LOCALE_COOKIE = "crm_locale";

export function normalizeLocale(v: string | null | undefined): Locale {
  if (!v) return "en";
  return v.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const entry = DICT[key] as readonly [string, string] | undefined;
  let s: string = entry ? entry[locale === "pt-BR" ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Tradução opcional por chave dinâmica (atributos, opções e objetos padrão). */
export function translateMaybe(locale: Locale, key: string | null | undefined, fallback: string): string {
  if (!key || !(key in DICT)) return fallback;
  return translate(locale, key as MessageKey);
}

